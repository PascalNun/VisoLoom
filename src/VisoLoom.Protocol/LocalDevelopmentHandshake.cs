using System.Buffers.Binary;
using System.Text;

namespace VisoLoom.Protocol;

// A bounded, local-only credential handoff. Never serialize it into scene or job records.
public static class LocalDevelopmentHandshake
{
    public const string PipeName = "VisoLoom-development-v1";
    public const int PayloadLength = 66;

    public static void ValidatePipeName(string name)
    {
        if (name.Length is < 1 or > 40 || name.Any(c => !char.IsAsciiLetterOrDigit(c) && c is not '-' and not '_'))
            throw new ArgumentException("The development pipe name must be short ASCII text without path separators.");
    }

    public static byte[] Encode(int port, string token)
    {
        if (port is < 1 or > 65535 || token.Length != 64 || token.Any(c => !char.IsAsciiHexDigit(c)))
            throw new ArgumentException("Automatic development connections require a valid port and a random 64-character hexadecimal token.");
        byte[] payload = new byte[PayloadLength];
        BinaryPrimitives.WriteUInt16BigEndian(payload, (ushort)port);
        Encoding.ASCII.GetBytes(token).CopyTo(payload, 2);
        return payload;
    }

    public static LocalDevelopmentCredentials Decode(byte[] payload)
    {
        if (payload.Length != PayloadLength)
            throw new ArgumentException("The development handshake has an unexpected length.");
        int port = BinaryPrimitives.ReadUInt16BigEndian(payload);
        string token = Encoding.ASCII.GetString(payload, 2, 64);
        if (port == 0 || token.Any(c => !char.IsAsciiHexDigit(c)))
            throw new ArgumentException("The development handshake is invalid.");
        return new(port, token);
    }
}

public sealed class LocalDevelopmentCredentials
{
    public Uri Endpoint { get; }
    public string Token { get; }

    internal LocalDevelopmentCredentials(int port, string token)
    {
        Endpoint = new Uri($"http://127.0.0.1:{port}/");
        Token = token;
    }

    // Avoid the credential-bearing ToString generated by a record.
    public override string ToString() => "Local development connection";
}
